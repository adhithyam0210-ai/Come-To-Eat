-- 9. ORDER ITEMS TABLE
CREATE TABLE IF NOT EXISTS order_items (
  id SERIAL PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  food_id INTEGER REFERENCES food_items(id),
  food_name TEXT NOT NULL,
  unit_price DECIMAL NOT NULL,
  quantity INTEGER NOT NULL,
  subtotal DECIMAL NOT NULL,
  selected_addons_json TEXT
);

-- 10. ORDER STATUS HISTORY TABLE
CREATE TABLE IF NOT EXISTS order_status_history (
  id SERIAL PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  old_status TEXT,
  new_status TEXT NOT NULL,
  comment TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. PAYMENTS TABLE
CREATE TABLE IF NOT EXISTS payments (
  id SERIAL PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  user_id REFERENCES users(id),
  amount DECIMAL NOT NULL,
  payment_method TEXT NOT NULL,
  transaction_id TEXT UNIQUE NOT NULL,
  status TEXT DEFAULT 'successful',
  gateway_response_json TEXT,
  refund_status TEXT DEFAULT 'none',
  refund_amount DECIMAL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. DELIVERY ORDERS TABLE
CREATE TABLE IF NOT EXISTS delivery_orders (
  id SERIAL PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  driver_name TEXT NOT NULL,
  driver_phone TEXT NOT NULL,
  current_status TEXT DEFAULT 'assigned',
  live_lat DECIMAL,
  live_lng DECIMAL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 13. COUPONS TABLE
CREATE TABLE IF NOT EXISTS coupons (
  id SERIAL PRIMARY KEY,
  code TEXT UNIQUE NOT NULL,
  discount_type TEXT NOT NULL,
  discount_value DECIMAL NOT NULL,
  min_order_value DECIMAL DEFAULT 0,
  max_discount DECIMAL,
  start_date DATE,
  end_date DATE,
  expires_at TIMESTAMPTZ,
  is_active INTEGER DEFAULT 1,
  times_used INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 14. OFFER BANNERS TABLE
CREATE TABLE IF NOT EXISTS offer_banners (
  id SERIAL PRIMARY KEY,
  title TEXT NOT NULL,
  tag TEXT NOT NULL DEFAULT 'PROMO',
  description TEXT,
  image_url TEXT,
  button_text TEXT DEFAULT 'Explore Menu',
  target_category TEXT,
  bg_color TEXT DEFAULT '#85926B',
  sort_order INTEGER DEFAULT 0,
  is_active INTEGER DEFAULT 1,
  branch_id INTEGER,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 15. HERO BANNER SLIDES TABLE
CREATE TABLE IF NOT EXISTS hero_slides (
  id SERIAL PRIMARY KEY,
  tag TEXT NOT NULL,
  script TEXT NOT NULL,
  title TEXT NOT NULL,
  desc_text TEXT NOT NULL,
  image_url TEXT,
  button_text TEXT DEFAULT 'Order Now',
  bg_color TEXT DEFAULT '#85926B',
  accent_text TEXT,
  target_category TEXT DEFAULT 'Burgers and Sandwiches',
  sort_order INTEGER DEFAULT 0,
  is_active INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 16. REVIEWS TABLE
CREATE TABLE IF NOT EXISTS reviews (
  id SERIAL PRIMARY KEY,
  user_id INTEGER REFERENCES users(id),
  user_name TEXT NOT NULL,
  rating INTEGER NOT NULL,
  comment TEXT NOT NULL,
  food_id INTEGER REFERENCES food_items(id),
  is_approved INTEGER DEFAULT 1,
  branch_id INTEGER,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 17. RESTAURANT SETTINGS TABLE
CREATE TABLE IF NOT EXISTS restaurant_settings (
  id SERIAL PRIMARY KEY,
  setting_key TEXT UNIQUE NOT NULL,
  setting_value TEXT NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

